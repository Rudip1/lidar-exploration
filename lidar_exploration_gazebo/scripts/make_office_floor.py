#!/usr/bin/env python3
"""Write worlds/office_floor.sdf and worlds/office_floor_walls.json: a 20 m x 14 m office floor (a corridor, six
rooms, furniture) as 1 m high, 0.1 m thick walls, plus the Gazebo systems the robot's lidar needs. The JSON holds the
wall centre lines for evaluate_exploration.py; the C++ tests have the same list in test/floor_plan.hpp.

    python3 scripts/make_office_floor.py      # from anywhere; commit the result
"""
import json
import math
from pathlib import Path

# Wall centre lines (ax, ay, bx, by), identical to lidar_exploration/test/floor_plan.hpp.
WALLS = [
    # outer walls
    (-10, -7, 10, -7), (10, -7, 10, 7), (10, 7, -10, 7), (-10, 7, -10, -7),
    # corridor y in [-1, 1], doors 1.4 m wide between centre lines
    (-10, 1, -7.45, 1), (-6.05, 1, -0.7, 1), (0.7, 1, 6.05, 1), (7.45, 1, 10, 1),
    (-10, -1, -6.2, -1), (-4.8, -1, 0.8, -1), (2.2, -1, 6.8, -1), (8.2, -1, 10, -1),
    # room dividers; the two north-east rooms share a door
    (-3.5, 1, -3.5, 7), (3.5, 1, 3.5, 4), (3.5, 5.4, 3.5, 7), (-3.5, -7, -3.5, -1), (3.5, -7, 3.5, -1),
    # furniture
    (-8, 4.5, -6, 4.5), (-1.5, 3.5, 0, 5), (7, 3, 7, 5.5),
    (-8.5, -4, -7, -5.5), (-1, -4.5, 1.5, -4.5), (5.5, -3, 6.5, -3), (8.5, -5, 8.5, -6.2)]
START = (-8.5, 0.0, 0.0)  # spawn pose (x, y, yaw) in launch/sim.launch.py
HEIGHT, THICKNESS = 1.0, 0.1


def wall(k, ax, ay, bx, by):
    length = math.hypot(bx - ax, by - ay)
    cx, cy, yaw = (ax + bx) / 2, (ay + by) / 2, math.atan2(by - ay, bx - ax)
    # The box is centred on the segment, so each face is THICKNESS / 2 = 5 cm from the line of the 2-D model.
    geom = f"<box><size>{length + THICKNESS:.3f} {THICKNESS} {HEIGHT}</size></box>"
    return f"""      <link name="wall_{k}">
        <pose>{cx:.3f} {cy:.3f} {HEIGHT / 2} 0 0 {yaw:.6f}</pose>
        <collision name="c"><geometry>{geom}</geometry></collision>
        <visual name="v"><geometry>{geom}</geometry>
          <material><ambient>0.7 0.7 0.7 1</ambient><diffuse>0.7 0.7 0.7 1</diffuse></material></visual>
      </link>"""


def main():
    links = "\n".join(wall(k, *w) for k, w in enumerate(WALLS))
    sdf = f"""<?xml version="1.0"?>
<!-- Generated by scripts/make_office_floor.py; do not edit by hand. -->
<sdf version="1.9">
  <world name="office_floor">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.85 0.85 0.8 1</ambient><diffuse>0.85 0.85 0.8 1</diffuse></material></visual>
      </link>
    </model>

    <model name="office_floor_walls">
      <static>true</static>
{links}
    </model>
  </world>
</sdf>
"""
    worlds = Path(__file__).resolve().parent.parent / "worlds"
    (worlds / "office_floor.sdf").write_text(sdf)
    rows = ",\n".join("    " + json.dumps(list(w)) for w in WALLS)
    (worlds / "office_floor_walls.json").write_text(
        f'{{\n  "thickness": {THICKNESS},\n  "start": {json.dumps(list(START))},\n  "walls": [\n{rows}\n  ]\n}}\n')
    print(f"wrote {worlds / 'office_floor.sdf'} and {worlds / 'office_floor_walls.json'}")


if __name__ == "__main__":
    main()
